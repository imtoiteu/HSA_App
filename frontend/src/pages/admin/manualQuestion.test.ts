import { describe, expect, it } from "vitest";
import { EMPTY_FORM, buildRecord, formProblems, parseOptions } from "./manualQuestion";

describe("manual question form", () => {
  const f = { ...EMPTY_FORM, stem_md: "Đơn vị của lực là", options: "A. N\nB. J\nC. W\nD. ", answer: "a" };

  it("parses option lines and drops empty ones", () => {
    expect(parseOptions(f.options)).toEqual([{ label: "A", md: "N" }, { label: "B", md: "J" }, { label: "C", md: "W" }]);
    expect(parseOptions("A. dòng 1\ntiếp dòng 2\nB) x")).toEqual([{ label: "A", md: "dòng 1\ntiếp dòng 2" }, { label: "B", md: "x" }]);
  });

  it("builds an import record; no code = generated by the server", () => {
    const r = buildRecord(f);
    expect(r).toMatchObject({ type: "single_choice", stem_md: "Đơn vị của lực là", answer: { kind: "labels", labels: ["A"] } });
    expect("external_id" in r).toBe(false);
    expect(buildRecord({ ...f, type: "numeric_response", answer: "2,5" }).answer).toEqual({ kind: "numeric", value: 2.5, text: "2,5" });
    expect(buildRecord({ ...f, type: "true_false_statements", answer: "a) Đúng b) Sai" }).answer)
      .toEqual({ kind: "text", text: "a) Đúng b) Sai" });
  });

  it("reports what would make the question unusable", () => {
    expect(formProblems(f)).toEqual([]);
    expect(formProblems({ ...f, stem_md: " " })).toContain("Chưa nhập đề bài.");
    expect(formProblems({ ...f, answer: "D" })).toContain("Đáp án D không có trong các phương án.");
    expect(formProblems({ ...f, options: "A. N" })[0]).toMatch(/ít nhất 2 phương án/);
    expect(formProblems({ ...f, answer: "A,B" })).toContain("Câu một đáp án chỉ được chọn một nhãn.");
    expect(formProblems({ ...f, type: "numeric_response", answer: "abc" })[0]).toMatch(/phải là một số/);
    expect(formProblems({ ...f, external_id: "có dấu cách" })[0]).toMatch(/Mã câu/);
  });
});
